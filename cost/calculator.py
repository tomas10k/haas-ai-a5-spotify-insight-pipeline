"""Required 100 review cost and runtime calculator.

  python3 cost/calculator.py            OFFLINE REPLAY (default): no API key, no model calls. Recomputes every
                                        cost from saved usage (cost/pilot_calls.jsonl) x editable rates (cost/rates.csv),
                                        then projects the full run from cost/assumptions.json. Writes cost/usage.csv + report.md
  python3 cost/calculator.py check      offline arithmetic checks (rates x2 => API x2; time and measured results unchanged)
  python3 cost/calculator.py pilot      PAID, explicit: runs the real pipeline on data/cost_100.csv twice
                                        (cold with an empty result cache, then warm), one worker, then replays.
Importing this file never makes a call.
"""
import csv, hashlib, json, math, sys, time
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COST = ROOT / "cost"
sys.path.insert(0, str(ROOT))
EXPECTED_SHA = "c884ac3b9be5066995d5063f96ad9af6e5e082975788c1684c4f6b6ea661dd0e"


def load_rates(multiplier=1.0):
    rates, meta = {}, {}
    for r in csv.DictReader(open(COST / "rates.csv")):
        rates[(r["model"], r["item"])] = float(r["price_per_unit_usd"]) * multiplier
        meta[(r["model"], r["item"])] = r
    return rates, meta


ITEMS = (("input", "input_tokens"), ("cached_input", "cached_input_tokens"), ("cache_write", "cache_write_tokens"), ("output", "output_tokens"))


def recompute(calls, rates):
    """item_cost = billed_units x price_per_unit, mutually exclusive items. Returns usage rows + per call cost."""
    rows = []
    for c in calls:
        c["_cost"] = 0.0
        for item, key in ITEMS:
            units = c.get(key) or 0
            if not units and item != "input":
                continue
            p = rates.get((c["model"], item))
            cost = units * p if p is not None else None
            rows.append({"pilot_run": c["pilot_run"], "request_id": c["request_id"], "role": c["role"], "step": c.get("step", c["role"]),
                         "model": c["model"], "outcome": c["outcome"], "item": item, "units": units, "unit": "token",
                         "price_per_unit_usd": p if p is not None else "MISSING RATE", "cost_usd": round(cost, 10) if cost is not None else "unknown"})
            c["_cost"] += cost or 0.0
    return rows


def money(x):
    return f"${x:,.4f}" if x < 10 else f"${x:,.2f}"


def replay(write=True, rate_multiplier=1.0, assumptions=None, quiet=False):
    rates, meta = load_rates(rate_multiplier)
    A = assumptions or json.loads((COST / "assumptions.json").read_text())
    if not (COST / "pilot_calls.jsonl").exists():
        print("No pilot measurements yet. Run the paid pilot first:  python3 cost/calculator.py pilot")
        return None
    calls = [json.loads(l) for l in open(COST / "pilot_calls.jsonl")]
    runs = json.loads((COST / "pilot_runs.json").read_text())
    recs = [json.loads(l) for l in open(COST / "pilot_records.jsonl")]
    usage = recompute(calls, rates)
    if write:
        with open(COST / "usage.csv", "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(usage[0].keys())); w.writeheader(); w.writerows(usage)
    L = []
    P = L.append
    P("# Cost and runtime calculator: measured 100 review pilot and full run projection\n")
    P(f"Generated by `python3 cost/calculator.py` (offline replay, no API calls). Rates: `cost/rates.csv`; usage: `cost/usage.csv`; assumptions: `cost/assumptions.json`.\n")
    # ---------------- measured ----------------
    completed = sum(r["status"] == "completed" for r in recs)
    P("## 1. Measured pilot (real calls)\n")
    P(f"* Input: `data/cost_100.csv`, SHA256 `{runs['input_sha256'][:16]}...` ({'matches' if runs['input_sha256'] == EXPECTED_SHA else 'DOES NOT MATCH'} manifest), {runs['ids']} IDs, {runs['unique_texts']} unique texts")
    P(f"* Records: {completed} completed, {len(recs) - completed} quarantined or failed; result cache hits on warm run: {runs['warm']['cache_hits']}")
    P(f"* Pilot run id `{runs['run_id']}`, workers 1, label_config `{runs['label_config']}`\n")
    P("| Run | Wall clock (s) | Model attempts | Failed attempts | New enrichment calls | API cost |")
    P("|---|---|---|---|---|---|")
    tot = {}
    for pr in ("cold", "warm"):
        cs = [c for c in calls if c["pilot_run"] == pr]
        tot[pr] = sum(c["_cost"] for c in cs)
        P(f"| {pr} | {runs[pr]['wall_clock_seconds']} | {len(cs)} | {sum(c['outcome'] == 'failed' for c in cs)} | "
          f"{sum(c['role'] == 'enrich' for c in cs)} | {money(tot[pr])} |")
    P("")
    P("### By stage (cold run)\n")
    P("| Stage / step | Provider | Model | Prompt version | Batch size | Workers | Attempts | Succeeded | Failed | Input tok | Output tok | Cost | Summed call seconds |")
    P("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    g = defaultdict(lambda: defaultdict(float))
    info = {}
    for c in calls:
        if c["pilot_run"] != "cold":
            continue
        k = (c["role"], c.get("step", c["role"]))
        d = g[k]; info[k] = c
        d["att"] += 1; d["ok"] += c["outcome"] == "succeeded"; d["fail"] += c["outcome"] == "failed"
        d["in"] += c.get("input_tokens") or 0; d["out"] += c.get("output_tokens") or 0; d["cost"] += c["_cost"]; d["sec"] += c.get("seconds") or 0
    batch = {"enrich": "1 review", "verify": "10 reviews", "group": "aggregates", "memo": "aggregates"}
    for k, d in g.items():
        c = info[k]
        P(f"| {k[0]} / {k[1]} | {c['provider']} | `{c['model']}` | {c['prompt_version']} | {batch.get(k[0], '')} | 1 | {int(d['att'])} | {int(d['ok'])} | "
          f"{int(d['fail'])} | {int(d['in']):,} | {int(d['out']):,} | {money(d['cost'])} | {d['sec']:.1f} |")
    P(f"| prepare, records, rank (code only) | local | none | | | 1 | 0 | | | | | $0 | stage seconds: {runs['cold']['stage_seconds']} |")
    wall = runs["cold"]["wall_clock_seconds"]
    P(f"\n* Cost per 1,000 input rows: **{money(tot['cold'] / runs['ids'] * 1000)}**; per completed record: **{money(tot['cold'] / max(completed, 1))}**")
    P(f"* Throughput (cold, end to end): {runs['ids'] / wall:.2f} rows/s; warm rerun: {runs['warm']['wall_clock_seconds']} s with {sum(c['role'] == 'enrich' for c in calls if c['pilot_run'] == 'warm')} new enrichment calls")
    P(f"* Summed call durations are not wall clock time; wall clock is measured with a clock around the whole run.")
    P(f"* Local compute: {A['local_compute']['device']}: {A['local_compute']['cost_usd']}. Separate from API spend; not counted as zero.\n")
    P("### Rates used (editable)\n\n| Model | Item | Price per unit (USD) | Quoted | Source | Checked |\n|---|---|---|---|---|---|")
    for (m, it), r in meta.items():
        P(f"| `{m}` | {it} | {r['price_per_unit_usd']} | {r['price_quoted']} | {r['source_url']} | {r['checked_date']} |")
    # ---------------- projection ----------------
    F, C = A["full_run"], A["controls"]
    cold = [c for c in calls if c["pilot_run"] == "cold"]
    rec_by_id = {r["review_id"]: r for r in recs}
    jev = [c for c in cold if c.get("step") == "jev_classify"]
    jev_ok = [c for c in jev if c["outcome"] == "succeeded"]
    texts = runs["unique_texts"]
    long_ids = set(runs.get("long_review_ids", []))
    tok_long = [c["input_tokens"] for c in jev_ok if c["review_ids"][0] in long_ids]
    tok_short = [c["input_tokens"] for c in jev_ok if c["review_ids"][0] not in long_ids]
    mean = lambda xs: sum(xs) / len(xs) if xs else 0
    jev_rate = rates[(jev[0]["model"], "input")] if jev else 0
    attempts_per_text = len(jev) / texts
    fb = [c for c in cold if c.get("step") == "haiku_fallback"]
    fb_texts = len({c["review_ids"][0] for c in fb if c["outcome"] == "succeeded"})
    fb_cost_each = (sum(c["_cost"] for c in fb) / max(len(fb), 1)) if fb else (900 * 1e-6 + 80 * 5e-6)
    ver = [c for c in cold if c["role"] == "verify"]
    ver_reviews = sum(len(c["review_ids"]) for c in ver if c["outcome"] == "succeeded")
    ver_each = sum(c["_cost"] for c in ver) / max(ver_reviews, 1)
    grp = sum(c["_cost"] for c in cold if c["role"] == "group")
    memo = sum(c["_cost"] for c in cold if c["role"] == "memo")
    enrich_secs = runs["cold"]["stage_seconds"].get("enrich", 1)
    thr1 = texts / enrich_secs  # texts per second, one worker
    P("\n## 2. Projections (estimates, not measurements)\n")
    P(f"Measured inputs: Jev input tokens per short text {mean(tok_short):.0f}, per long text {mean(tok_long):.0f}; Jev attempts per text {attempts_per_text:.3f}; "
      f"Haiku fallback rate {fb_texts / texts:.2%} at {money(fb_cost_each)} per call; verification {money(ver_each)} per review; group {money(grp)} and memo {money(memo)} once; "
      f"enrichment throughput {thr1:.2f} texts/s at 1 worker.\n")
    out = {}
    for label, F in (("Declared final scope (100,000 reviews)", A["declared_scope"]), ("Full corpus (for comparison, not run)", A["full_run"])):
        out.update(_project(P, label, F, A, C, mean(tok_short), mean(tok_long), attempts_per_text, jev_rate, fb_texts / texts,
                            fb_cost_each, ver_each, grp, memo, thr1, money, prefix="" if F is A["declared_scope"] else "full_"))
    _refresh(P, A, money)
    P(f"\nFixed overhead (group naming, memo) is counted once, never per review. Workers shorten elapsed time but do not lower cost; "
      f"elapsed time is capped by {C['max_requests_per_second']} requests/s shared across workers.\n")
    P("## 4. Controls\n")
    P(f"* Spend cap: **${C['spend_cap_usd']:.2f}**, enforced by one shared ledger that reserves worst case cost before every call and stops admitting work at the cap (progress is saved).")
    P(f"* Output token caps: Haiku calls {C['haiku_output_token_cap']}, memo (GPT-6 Luna, reasoning included) {C.get('memo_output_token_cap')}. Jev output is free and has no output cap.")
    P(f"* Maximum workers: {C['max_workers']}; maximum requests per second: {C['max_requests_per_second']}.")
    P(f"* Haiku fallback fraction cap: {C['fallback_fraction_cap']:.0%} of processed texts. Invalid output: one retry then quarantine. Transient errors: up to 4 attempts with backoff and jitter, each logged.")
    P(f"* Decision rule: refresh the projection after 500 and 10,000 reviews (section 3), then start the final run only if the conservative scenario for the declared scope stays under the cap.")
    txt = "\n".join(L) + "\n"
    if write:
        (COST / "report.md").write_text(txt)
    if not quiet:
        print(txt)
    return {"cold": tot["cold"], "warm": tot["warm"], "cold_seconds": runs["cold"]["wall_clock_seconds"],
            "projection": {f"{k[0]}_{'reuse' if k[1] else 'noreuse'}": v for k, v in out.items()}}


def _project(P, label, F, A, C, tok_s, tok_l, attempts_per_text, jev_rate, fb_rate, fb_cost_each, ver_each, grp, memo, thr1, money, prefix=""):
    P(f"### {label}\n")
    P(f"Scope: {F['rows']:,} rows; {F['nonempty']:,} nonempty classifications; {F['empty_quarantined']} empty texts quarantined by code; "
      f"{F['distinct_texts']:,} distinct texts after valid exact text reuse. Share of distinct texts over 200 characters (Jev also picks a quote sentence): {F['share_long_texts_over_200_chars']:.2%}.\n")
    P("| Scenario | Reuse | Jev classify | Haiku fallback | Verify | Group | Memo | **Total API** | Enrich hours | Over budget? |")
    P("|---|---|---|---|---|---|---|---|---|---|")
    out = {}
    for name, S in A["scenarios"].items():
        for reuse in (True, False):
            n = F["distinct_texts"] if reuse else F["nonempty"]
            share = F["share_long_texts_over_200_chars"]
            tok = (1 - share) * tok_s + share * (tok_l or tok_s)
            att = max(attempts_per_text, 1 + S["min_retry_rate"])
            c_jev = n * tok * S["token_multiplier"] * att * jev_rate
            fr = C["fallback_fraction_cap"] if S["fallback_rate"] == "cap" else min(fb_rate, C["fallback_fraction_cap"])
            c_fb = n * fr * fb_cost_each * S["token_multiplier"]
            sample = min(A["verification"]["sample_reviews"], max(20, round(0.01 * F["distinct_texts"])))
            c_ver = sample * ver_each * S["token_multiplier"]
            c_grp = grp * A["group_scale_factor"]
            c_memo = memo * S["memo_attempts"]
            total = c_jev + c_fb + c_ver + c_grp + c_memo
            eff = min(thr1 * S["workers"], C["max_requests_per_second"] / max(att, 1))
            hours = n / eff / 3600 + F["prepare_seconds_measured_full_file"] / 3600
            over = "**YES: exceeds cap**" if total > C["spend_cap_usd"] else "no"
            out[(prefix + name, reuse)] = total
            P(f"| {name} ({S['workers']} workers) | {'exact text reuse' if reuse else 'no reuse'} | {money(c_jev)} | {money(c_fb)} | {money(c_ver)} | "
              f"{money(c_grp)} | {money(c_memo)} | **{money(total)}** | {hours:.1f} | {over} |")
    P("")
    return out


def _refresh(P, A, money):
    """Section 3: the projection refreshed from real larger runs (measured, not modeled)."""
    P("## 3. Refresh from larger measured runs\n")
    P("| Run | Distinct texts enriched | Enrich attempts | Failed attempts | Enrich API cost | Cost per distinct text | Haiku fallback calls | Workers | Enrich texts/s | Projected declared scope enrich cost at this rate |")
    P("|---|---|---|---|---|---|---|---|---|---|")
    for size, rd in A.get("refresh_runs", {}).items():
        d = ROOT / rd
        if not (d / "calls.jsonl").exists():
            P(f"| {size} (`{rd}`) | not run yet | | | | | | | | |"); continue
        calls = [json.loads(l) for l in open(d / "calls.jsonl")]
        en = [c for c in calls if c["role"] == "enrich"]
        cost = sum(c.get("cost_usd") or 0 for c in en)
        texts = sum(1 for _ in open(d / "enrich" / "enriched_texts.jsonl")) if (d / "enrich" / "enriched_texts.jsonl").exists() else 0
        logs = [json.loads(l) for l in open(d / "run_log.jsonl") if '"stage": "enrich"' in l and '"completed_now"' in l]
        speed = "; ".join(f"{g['workers']}w: {g['completed_now'] / g['seconds']:.1f}" for g in logs if g.get("seconds") and g["completed_now"])
        per = cost / max(texts, 1)
        P(f"| {size} (`{rd}`) | {texts:,} | {len(en):,} | {sum(c['outcome'] == 'failed' for c in en)} | {money(cost)} | ${per:.6f} | "
          f"{sum(c.get('step') == 'haiku_fallback' for c in en)} | {', '.join(sorted({str(g['workers']) for g in logs}))} | {speed} | "
          f"{money(per * A['declared_scope']['distinct_texts'])} |")
    P("")


def check():
    """The instructor's arithmetic checks, offline: doubling API rates doubles API spend and leaves time unchanged;
    changing projected volume leaves the measured pilot unchanged."""
    a = replay(write=False, quiet=True)
    b = replay(write=False, rate_multiplier=2.0, quiet=True)
    A = json.loads((COST / "assumptions.json").read_text())
    for k in ("full_run", "declared_scope"):
        A[k]["distinct_texts"] *= 2; A[k]["nonempty"] *= 2
    c = replay(write=False, assumptions=A, quiet=True)
    res = {"api_cold_x1": round(a["cold"], 8), "api_cold_x2_rates": round(b["cold"], 8),
           "doubles": abs(b["cold"] - 2 * a["cold"]) < 1e-12, "time_unchanged": a["cold_seconds"] == b["cold_seconds"],
           "projection_doubles_too": abs(b["projection"]["base_reuse"] - 2 * a["projection"]["base_reuse"]) < 1e-9,
           "measured_unchanged_when_volume_doubles": a["cold"] == c["cold"] and a["cold_seconds"] == c["cold_seconds"]}
    print(json.dumps(res, indent=2))
    (COST / "arithmetic_check.json").write_text(json.dumps(res, indent=2) + "\n")
    return res


def pilot():
    from pipeline.run import run
    from pipeline.common import file_sha, read_jsonl
    src = ROOT / "data" / "cost_100.csv"
    sha = file_sha(src)
    if sha != EXPECTED_SHA:
        sys.exit(f"cost_100.csv checksum {sha} does not match manifest; refusing to run")
    run_id = "pilot_" + time.strftime("%Y%m%d_%H%M%S")
    run_dir = ROOT / "runs" / run_id
    assert not run_dir.exists(), "pilot must start with an empty result cache"
    print(f"PAID PILOT: {run_id} (cold run, empty cache, 1 worker)")
    m_cold = run(str(src), run_id, workers=1)
    if m_cold.get("stopped"):
        sys.exit(f"PILOT STOPPED during the cold run: {m_cold['stopped']}\nNothing was written to cost/. Fix the cause, then run the pilot again (it starts a new empty run).")
    n_cold = sum(1 for _ in open(run_dir / "calls.jsonl"))
    print("PAID PILOT: warm rerun with saved results (expect zero new enrichment calls)")
    m_warm = run(str(src), run_id, workers=1)
    calls = [json.loads(l) for l in open(run_dir / "calls.jsonl")]
    with open(COST / "pilot_calls.jsonl", "w") as f:
        for i, c in enumerate(calls):
            c["pilot_run"] = "cold" if i < n_cold else "warm"
            f.write(json.dumps(c) + "\n")
    keep = ("review_id", "source_sha256", "status", "topic", "intent", "sentiment", "severity", "entities", "evidence_quote",
            "needs_review", "label_config", "cache_source_id", "reason")
    n = 0
    with open(COST / "pilot_records.jsonl", "w") as f:
        for name in ("enriched.jsonl", "quarantine.jsonl"):
            for r in read_jsonl(run_dir / "records" / name):
                f.write(json.dumps({k: r[k] for k in keep if k in r}, ensure_ascii=False) + "\n"); n += 1
    texts = list(read_jsonl(run_dir / "prepare" / "texts.jsonl"))
    with open(COST / "pilot_runs.json", "w") as fh:
        json.dump({"run_id": run_id, "input_sha256": sha, "ids": n, "unique_texts": len(texts), "label_config": m_cold["label_config"],
               "long_review_ids": [t["first_review_id"] for t in texts if len(t["review_text"]) > 200],
               "cold": {"wall_clock_seconds": m_cold["wall_clock_seconds"], "stage_seconds": m_cold["stage_seconds"]},
               "warm": {"wall_clock_seconds": m_warm["wall_clock_seconds"], "stage_seconds": m_warm["stage_seconds"],
                        "cache_hits": len(texts)}}, fh, indent=2)
    replay()


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "pilot":
        pilot()
    elif len(sys.argv) > 1 and sys.argv[1] == "check":
        check()
    else:
        replay()
